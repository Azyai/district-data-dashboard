import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.slice(2).includes('--check');
const readJson = async (path) => JSON.parse(await readFile(resolve(root, path), 'utf8'));
const catalog = await readJson('contracts/response-codes.json');
const openapi = await readJson('contracts/openapi.json');

const names = new Set();
const codes = new Set();

for (const { name, code, httpStatus, message } of catalog) {
  const isSuccess = name === 'OK';
  if (!/^[A-Z][A-Z_0-9]+$/.test(name) || names.has(name) || codes.has(code) ||
      typeof message !== 'string' || !message.trim() || /[\p{Cc}\p{Zl}\p{Zp}]/u.test(message) ||
      !Number.isInteger(httpStatus) ||
      (isSuccess ? code !== '0' || httpStatus !== 200 || message !== 'success' :
        code !== name || httpStatus < 400 || httpStatus > 599)) {
    throw new Error('Invalid API code entry ' + name);
  }
  names.add(name);
  codes.add(code);
}

if (!names.has('OK')) {
  throw new Error('The catalog must contain OK');
}

const expectedErrors = [...codes].filter((code) => code !== '0').sort();
const documentedErrors = [...openapi.components.schemas.ErrorBody.properties.code.enum].sort();
if (JSON.stringify(expectedErrors) !== JSON.stringify(documentedErrors)) {
  throw new Error('The OpenAPI error codes must match the shared API code catalog');
}

const javaEntries = catalog.map(
  ({ name, code, httpStatus, message }) =>
    '    ' + name + '(' + JSON.stringify(code) + ', ' + httpStatus + ', ' + JSON.stringify(message) + ')',
);

const java = '// Generated by scripts/generate-api-codes.mjs. Edit contracts/response-codes.json.\n' +
  'package gov.district.dashboard.platform.api;\n\n' +
  'public enum ApiCode {\n' + javaEntries.join(',\n') + ';\n\n' +
  '    private final String code;\n    private final int httpStatus;\n    private final String message;\n\n' +
  '    ApiCode(String code, int httpStatus, String message) {\n' +
  '        this.code = code;\n        this.httpStatus = httpStatus;\n        this.message = message;\n    }\n\n' +
  '    public String code() {\n        return code;\n    }\n\n' +
  '    public int httpStatus() {\n        return httpStatus;\n    }\n\n' +
  '    public String message() {\n        return message;\n    }\n}\n';

const tsEntries = Object.fromEntries(catalog.map(({ code, httpStatus, message }) =>
  [code, { httpStatus, message }],
));
const typescript = '// Generated by scripts/generate-api-codes.mjs. Edit contracts/response-codes.json.\n' +
  'export const apiCodes = ' + JSON.stringify(tsEntries, null, 2) + ' as const;\n\n' +
  'export type ApiCode = keyof typeof apiCodes;\n';

const outputs = {
  'backend/platform-core/src/main/java/gov/district/dashboard/platform/api/ApiCode.java': java,
  'frontend/src/api/generated/codes.ts': typescript,
};

for (const [relative, expected] of Object.entries(outputs)) {
  const target = resolve(root, relative);
  if (check) {
    const actual = await readFile(target, 'utf8').catch((error) => {
      if (error.code !== 'ENOENT') throw error;
      return '';
    });
    if (actual.replaceAll('\r\n', '\n') !== expected) {
      throw new Error('Generated file is out of date: ' + relative);
    }
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, expected, 'utf8');
  }
}
